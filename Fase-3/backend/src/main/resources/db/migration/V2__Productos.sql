CREATE TABLE PRODUCTOS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO VARCHAR2(30) NOT NULL UNIQUE,
    NOMBRE VARCHAR2(150) NOT NULL,
    CATEGORIA VARCHAR2(50) NOT NULL,
    PRECIO NUMBER(10) NOT NULL,
    STOCK_ACTUAL NUMBER(10) NOT NULL,
    STOCK_MINIMO NUMBER(10) NOT NULL,
    ESTADO VARCHAR2(30) NOT NULL,
    IMAGEN VARCHAR2(500),
    DESCRIPCION VARCHAR2(1000),

    CONSTRAINT CHK_PRODUCTO_PRECIO
        CHECK (PRECIO >= 0),

    CONSTRAINT CHK_PRODUCTO_STOCK_ACTUAL
        CHECK (STOCK_ACTUAL >= 0),

    CONSTRAINT CHK_PRODUCTO_STOCK_MINIMO
        CHECK (STOCK_MINIMO >= 0),

    CONSTRAINT CHK_PRODUCTO_ESTADO
        CHECK (ESTADO IN ('Disponible', 'Stock bajo', 'Sin stock'))
);

