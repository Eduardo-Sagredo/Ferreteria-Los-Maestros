-- Tabla principal de pedidos
CREATE TABLE PEDIDOS (
                         ID RAW(16) NOT NULL,
                         NUMERO_PEDIDO VARCHAR2(20) NOT NULL,
                         CLIENTE_NOMBRE VARCHAR2(150) NOT NULL,
                         FECHA TIMESTAMP(6) NOT NULL,
                         TOTAL NUMBER(10, 0) NOT NULL,
                         ENTREGA VARCHAR2(30) NOT NULL,
                         ESTADO VARCHAR2(30) NOT NULL,
                         METODO_PAGO VARCHAR2(30),
                         CONSTRAINT PK_PEDIDOS PRIMARY KEY (ID),
                         CONSTRAINT UK_PEDIDOS_NUMERO UNIQUE (NUMERO_PEDIDO)
);

-- Tabla de detalle de productos por pedido
CREATE TABLE DETALLE_PEDIDOS (
                                 ID RAW(16) NOT NULL,
                                 PEDIDO_ID RAW(16) NOT NULL,
                                 PRODUCTO_ID NUMBER(19, 0) NOT NULL,
                                 CANTIDAD NUMBER(10, 0) NOT NULL,
                                 PRECIO_UNITARIO NUMBER(10, 0) NOT NULL,
                                 CONSTRAINT PK_DETALLE_PEDIDOS PRIMARY KEY (ID),
                                 CONSTRAINT FK_DETALLE_PEDIDO FOREIGN KEY (PEDIDO_ID)
                                     REFERENCES PEDIDOS (ID) ON DELETE CASCADE,
                                 CONSTRAINT FK_DETALLE_PRODUCTO FOREIGN KEY (PRODUCTO_ID)
                                     REFERENCES PRODUCTOS (ID)
);

